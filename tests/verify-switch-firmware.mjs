import assert from 'node:assert/strict';import {build} from 'esbuild';
const built=await build({entryPoints:['src/themes/switchFirmware.ts'],bundle:true,write:false,format:'esm'});
const {firmwarePanes}=await import('data:text/javascript;base64,'+Buffer.from(built.outputFiles[0].text).toString('base64'));
assert.equal(firmwarePanes({},'auto').L_BtnSplay,undefined);
assert.equal(firmwarePanes({},'modern').L_BtnVgc.Position.X,234);
assert.equal(firmwarePanes({L_BtnVgc:{Position:{X:200}}},'auto').L_BtnVgc.Position.X,200);
assert.equal(firmwarePanes({L_BtnVgc:{Position:{X:200}}},'classic').L_BtnVgc,undefined);
assert.equal(firmwarePanes({L_BtnLR:{Visible:false}},'auto').L_BtnSplay,undefined);
assert.equal(firmwarePanes({L_BtnLR:{Visible:true}},'auto').L_BtnLR.Visible,true,'Automatic must retain a theme-authored legacy NSO applet');
assert.equal(firmwarePanes({L_BtnLR:{Visible:true}},'classic').L_BtnLR,undefined,'Explicit six-applet mode must still override the authored legacy NSO slot');
assert.equal(firmwarePanes({},'classic').N_GameRoot.Position.Y,38);
assert.equal(firmwarePanes({},'classic')['game:P_IconGame'].Size.X,256);
assert.equal(firmwarePanes({N_Icon_00:{Position:{}}},'classic').N_Icon_00.Position.X,undefined);
assert.equal(firmwarePanes({N_System:{Position:{Y:-186}}},'modern').N_System.Position.X,undefined);
assert(firmwarePanes({},'auto',2000).L_BtnSplay,'Declared firmware 20 must select modern geometry without relying on new applet patch names');
assert.equal(firmwarePanes({},'classic',2000).L_BtnSplay,undefined,'Explicit user choice must override declared firmware');
assert.equal(firmwarePanes({},'modern',undefined,true).L_BtnSplay.Visible,false,'Legacy applet requests must hide unrequested modern applets');
console.log('PASS firmware layout detection, overrides, and imported positions');
const originBuilt=await build({entryPoints:['src/themes/switchPaneOrigin.ts'],bundle:true,write:false,format:'esm'});
const {switchPaneOrigin}=await import('data:text/javascript;base64,'+Buffer.from(originBuilt.outputFiles[0].text).toString('base64'));
assert.deepEqual(switchPaneOrigin(2),{x:2,y:0,parentX:0,parentY:0},'HUD right alignment must not become a bottom parent anchor');
assert.deepEqual(switchPaneOrigin(16),{x:0,y:0,parentX:1,parentY:0},'Parent-left alignment must not become an own-top origin');
assert.deepEqual(switchPaneOrigin(0b10100101),{x:1,y:1,parentX:2,parentY:2});
console.log('PASS native pane origin fields');
