import {build} from 'esbuild';
import assert from 'node:assert/strict';
import {mkdirSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
mkdirSync('out/bug-regressions',{recursive:true});
const result=await build({stdin:{contents:'export {loadLibrary} from "./src/library";',resolveDir:process.cwd()},bundle:true,write:false,format:'esm',platform:'node',alias:{'@decky/api':'./preview/stubs/api.ts','@decky/ui':'./preview/stubs/ui.tsx'}});
const file=resolve('out/bug-regressions/demo-library.mjs');writeFileSync(file,result.outputFiles[0].text);
globalThis.window=new EventTarget();
globalThis.appStore={};
const game={appid:1,app_type:1,display_name:'Game',installed:true},demo={appid:2,app_type:8,display_name:'Mortuus Demo',installed:true},hidden={appid:3,app_type:8,display_name:'Hidden Demo',installed:true},tool={appid:4,app_type:4,display_name:'Proton',installed:true},app={appid:5,app_type:2,display_name:'Application',installed:true};
globalThis.collectionStore={GetCollection:key=>key==='type-games'?{allApps:[game,demo]}:key==='hidden'?{allApps:[hidden]}:undefined,allAppsCollection:{allApps:[game,demo,hidden,tool,app]},userCollections:[]};
const {loadLibrary}=await import(pathToFileURL(file));
const library=loadLibrary('installed','alpha',100);
assert.deepEqual(library.games.map(g=>g.appid).sort(),[1,2]);
assert.equal(library.games.filter(g=>g.appid===2).length,1,'A demo included by multiple Steam collections appears once');
assert.equal(library.apps.length,1);assert.equal(library.apps[0].appid,5);
assert.equal(library.all.some(g=>g.appid===3),false,'Hidden demos stay excluded from normal views');
assert.equal(loadLibrary('col:hidden','alpha',100).games.some(g=>g.appid===3),true,'Explicit Hidden view still includes demos');
assert.equal(library.all.some(g=>g.appid===4),false,'Tools are not mistaken for demos');
console.log('PASS installed demos are games; duplicate entries deduplicate; hidden demos and tools stay excluded');
