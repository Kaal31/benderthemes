import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { startPreviewServer } from '../preview/server.mjs';
const themes = ['vita','ps2','ps3','psp','ps4','ps5','xbox','x360','aero','aero2','dial','castle','republic','minecraft','pain','nazarick'];
const {server,url} = await startPreviewServer();
const browser = await chromium.launch({headless:true});
try {
  const page = await browser.newPage({viewport:{width:1304,height:930}});
  const errors=[]; page.on('pageerror', e=>errors.push(String(e)));
  await page.goto(url);
  await page.locator('[data-dht-root]').waitFor();
  mkdirSync('out/theme-previews/pages',{recursive:true});
  for (const theme of themes) {
    await page.evaluate(theme=>window.__updateTheme({theme,animations:false}),theme);
    await page.evaluate(()=>window.__openPlace('settings'));
    await page.locator('.dht-destination[data-place=settings]').waitFor();
    await page.locator('.dht-destination-row').filter({hasText:/^Collections$/}).click();
    await page.locator('.dht-menu-item').filter({hasText:/^Favorites \(/}).click();
    assert.equal(await page.evaluate(theme=>window.__getThemeSettings().themeCollections[theme].source,theme),'col:favorite');
    const ids=await page.evaluate(()=>window.__getThemeLibrary().games.map(g=>g.appid));
    assert.ok(ids.length>0);
    await page.locator('.dht-destination-row').filter({hasText:/^Collections$/}).click();
    await page.getByText('Choose multiple collections',{exact:true}).click();
    await page.locator('.dht-menu-item').filter({hasText:/^RPGs/}).click();
    await page.getByText('Done',{exact:true}).click();
    const combined=await page.evaluate(()=>window.__getThemeLibrary().games.map(g=>g.appid));
    assert.ok(combined.length>ids.length);
    assert.equal(new Set(combined).size,combined.length);
    assert.ok(ids.every(id=>combined.includes(id)));
    await page.locator('.dht-destination-row').filter({hasText:/^Icon size$/}).click();
    await page.getByText('75%',{exact:true}).click();
    assert.equal(await page.evaluate(theme=>window.__getThemeSettings().iconSizes[theme],theme),75);
    assert.equal(await page.locator('.dht-safe-area').evaluate(el=>getComputedStyle(el).getPropertyValue('--dht-icon-scale').trim()),'0.75');
    await page.evaluate(()=>window.__openPlace('library'));
    await page.locator('.dht-destination[data-place=library]').waitFor();
    assert.equal(await page.locator('.dht-destination-row').count(),combined.length);
    await page.locator('[data-dht-root]').screenshot({path:`out/theme-previews/pages/${theme}-library.png`});
    await page.keyboard.press('Escape');
    console.log(`PASS ${theme}: collections, combined games, icon setting, themed library`);
  }
  await page.evaluate(()=>window.__updateTheme({theme:'minecraft',iconSizes:{...window.__getThemeSettings().iconSizes,minecraft:110}}));
  const thumbnail=page.locator('.mc-thumbnail').first();
  assert.equal(await thumbnail.evaluate(el=>getComputedStyle(el).scale),'1.1');
  await page.evaluate(()=>window.__openPlace('friends'));
  await page.locator('.dht-destination[data-place=friends]').waitFor();
  assert.equal(await page.locator('.dht-destination header').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(41, 43, 46)');
  await page.locator('[data-dht-root]').screenshot({path:'out/theme-previews/pages/minecraft-friends.png'});
  await page.keyboard.press('Escape');
  await page.evaluate(()=>window.__openStore());
  await page.locator('.dht-store').waitFor();
  await page.waitForTimeout(500);
  await page.locator('[data-dht-root]').screenshot({path:'out/theme-previews/pages/minecraft-store.png'});
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Hub',exact:true}).first().click();
  await page.locator('.dht-market').waitFor();
  assert.equal(await page.locator('.market-art b').count(),0);
  assert.equal(await page.locator('.dht-market h1').textContent(),'Hub');
  await page.locator('[data-dht-root]').screenshot({path:'out/theme-previews/hub.png'});
  await page.evaluate(()=>{window.__themeCatalog.themes.find(t=>t.id==='ps5').compatible=false;});
  await page.locator('.market-card').filter({hasText:/^PS5/}).click();
  assert.equal(await page.locator('.market-primary').textContent(),'Coming soon');
  assert.equal(await page.locator('.market-primary').isDisabled(),true);
  await page.locator('[data-dht-root]').screenshot({path:'out/theme-previews/hub-coming-soon.png'});
  assert.deepEqual(errors,[]);
} finally {await browser.close();server.close();}
