import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { launch } from './browser.mjs';
import { startPreviewServer } from '../preview/server.mjs';
const { server, url } = await startPreviewServer();
const browser = await launch();
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  const errors = [];
  page.on('pageerror', e => errors.push(String(e)));
  await page.goto(url.replace('preview.html', 'community-updates.html'));
  const community = page.getByRole('region', { name: 'Community themes' });
  await community.getByText('UI overhaul', { exact: true }).waitFor();
  assert.equal(await community.getByRole('button', { name: 'Update', exact: true }).count(), 0);
  await community.getByRole('button', { name: 'Check all theme updates' }).click();
  await community.getByText('2 theme updates available', { exact: false }).waitFor();
  assert.equal(await community.getByRole('button', { name: 'Update', exact: true }).count(), 2);
  assert.equal(await community.getByRole('alertdialog').count(), 0);
  await community.getByRole('button', { name: 'Update', exact: true }).first().click();
  await community.getByText('1 theme update available', { exact: false }).waitFor();
  await community.getByRole('button', { name: 'Restore previous version' }).first().click();
  await community.getByText('2 theme updates available', { exact: false }).waitFor();
  await page.getByRole('button', { name: 'GitHub: Online' }).click();
  await community.getByRole('button', { name: 'Check all theme updates' }).click();
  await community.getByText('GitHub unavailable; showing saved catalog.', { exact: true }).waitFor();
  assert.equal(await community.getByRole('button', { name: 'Update', exact: true }).count(), 2);
  await page.getByRole('button', { name: /^Updates/ }).click();
  await page.getByRole('region', { name: 'Hub updates' }).getByRole('heading', { name: '2 updates available', exact: true }).waitFor();
  mkdirSync('out/community-previews', { recursive: true });
  await page.screenshot({ path: 'out/community-previews/hub-updates-panel.png' });
  await page.getByRole('button', { name: 'Theme Hub', exact: true }).click();
  await page.getByRole('tab', { name: /Your themes/ }).click();
  await page.locator('.dht-hub-card').filter({ hasText: 'Neon Drive · sample' }).click();
  await page.getByRole('button', { name: 'Update theme', exact: false }).waitFor();
  await page.getByRole('button', { name: 'Update theme', exact: false }).click();
  await page.getByRole('heading', { name: 'Theme activated', exact: true }).waitFor();
  assert.equal(await page.evaluate(() => window.__getThemeSettings().activeTheme), 'community-preview');
  await page.getByRole('button', { name: 'Open Community', exact: true }).click();
  await page.getByRole('tab', { name: /Your themes/ }).click();
  await page.locator('.dht-hub-card').filter({ hasText: 'Neon Drive · sample' }).click();
  await page.getByRole('button', { name: 'Activate theme', exact: false }).waitFor();
  mkdirSync('out/community-previews', { recursive: true });
  await page.screenshot({ path: 'out/community-previews/update-system.png' });
  assert.deepEqual(errors, []);
  console.log('PASS: update discovery, asset-only update, direct native install, rollback, offline cache, Updates panel');
} finally { await browser.close(); server.close(); }
