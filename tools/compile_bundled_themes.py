"""Extract React theme styles and preserve the original direct-DOM GameCube renderer."""
import json
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]
IDS=('blue-glass','gameamp','gamecube','ios6','old-big-picture','santa-express','wiiflow-default')

def generate():
 styles={}
 for ident in IDS:
  folder=ROOT/'themes'/ident
  html=(folder/'index.html').read_text(encoding='utf-8')
  parts=[]
  for link in re.findall(r'<link\b[^>]*>',html,re.I):
   if re.search(r'rel=["\']stylesheet',link,re.I):
    href=re.search(r'href=["\']([^"\']+)',link)[1].split('?')[0]
    parts.append((folder/href).read_text(encoding='utf-8'))
  parts+=re.findall(r'<style[^>]*>(.*?)</style>',html,re.S|re.I)
  styles[ident]='\n'.join(parts)
 (ROOT/'src/engine/bundledStyles.generated.ts').write_text('// Generated visual styles only.\nexport const bundledStyles = '+json.dumps(styles)+';\n',encoding='utf-8')
 snow=(ROOT/'themes/santa-express/vendor/snowflakes.js').read_text(encoding='utf-8')
 (ROOT/'src/themes/santaSnow.generated.ts').write_text('// @ts-nocheck\n'+snow.replace('window.SantaSnowProgram = SnowProgram;','export default SnowProgram;'),encoding='utf-8')
GLOBALS='window document parent self globalThis location navigator performance crypto console Image Audio URL Blob MediaSource AbortController CustomEvent Event MutationObserver ResizeObserver IntersectionObserver requestAnimationFrame cancelAnimationFrame setTimeout clearTimeout setInterval clearInterval addEventListener removeEventListener dispatchEvent getComputedStyle matchMedia fetch ThemeHub SantaSnowProgram'.split()

def generate_original_surfaces():
 out=['// Generated by tools/compile_bundled_themes.py.\n// @ts-nocheck\nexport const bundledThemes = {']
 for ident in ('gamecube','wiiflow-default'):
  folder=ROOT/'themes'/ident
  html=(folder/'index.html').read_text(encoding='utf-8')
  body=re.search(r'<body([^>]*)>(.*?)</body>',html,re.S|re.I)
  markup=re.sub(r'<script\b[^>]*>.*?</script>','',body[2],flags=re.S|re.I)
  styles=[]
  for link in re.findall(r'<link\b[^>]*>',html,re.I):
   if re.search(r'rel=["\']stylesheet',link,re.I):
    href=re.search(r'href=["\']([^"\']+)',link)[1].split('?')[0]
    styles.append((folder/href).read_text(encoding='utf-8'))
  styles+=re.findall(r'<style[^>]*>(.*?)</style>',html,re.S|re.I)
  out.append(json.dumps(ident)+':{html:'+json.dumps(markup)+',bodyAttributes:'+json.dumps(body[1])+',css:'+json.dumps('\n'.join(styles))+',scripts:[')
  for attrs,code in re.findall(r'<script\b([^>]*)>(.*?)</script>',html,re.S|re.I):
   src=re.search(r'src=["\']([^"\']+)',attrs)
   if src:code=(folder/src[1].split('?')[0]).read_text(encoding='utf-8')
   # These scripts now measure their own native surface, not Steam's entire window.
   code=re.sub(r'(?<![\w.$])inner(Width|Height)\b',r'window.inner\1',code)
   out.append('function(scope){const {'+','.join(GLOBALS)+'}=scope;\n'+code+'\n},')
  out.append(']},')
 out.append('};\n')
 (ROOT/'src/engine/bundledThemes.generated.ts').write_text('\n'.join(out),encoding='utf-8')
if __name__=='__main__':
 generate()
 generate_original_surfaces()
