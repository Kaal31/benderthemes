"""Compile the trusted, bundled iOS 6 UI into its native component runtime."""
from pathlib import Path
import json, re
root=Path(__file__).resolve().parents[1]
theme=root/'themes/ios6'
html=(theme/'index.html').read_text(encoding='utf-8')
body=re.search(r'<body>(.*?)<script',html,re.S).group(1)
css=(theme/'style.css').read_text(encoding='utf-8').replace(':root',':host').replace('body','.ios6-body')
parts=['// @ts-nocheck','// Generated by tools/build_ios6_native.py. No iframe or dynamic code evaluation.', 'export const ios6Markup='+json.dumps(body)+';', 'export const ios6Css='+json.dumps(css)+';', 'export function runIOS6Native(env) {', 'const {document,window,parent,setTimeout,clearTimeout,setInterval,clearInterval,MutationObserver,location}=env;']
for name in ['system-icons','springboard-pages','audio','video','pages','app','notification-center']:
 source=(theme/(name+'.js')).read_text(encoding='utf-8')
 source=re.sub(r'''(['"])test-video\.mp4\1''', 'env.mediaUrl("test-video.mp4")', source)
 source=source.replace('innerWidth','env.innerWidth').replace('innerHeight','env.innerHeight')
 parts.append(source)
parts.append('}')
(root/'src/themes/ios6NativeRuntime.ts').write_text('\n'.join(parts),encoding='utf-8')
