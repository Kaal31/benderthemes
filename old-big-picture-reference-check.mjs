import assert from 'node:assert/strict';
import {mkdirSync} from 'node:fs';
import {launch} from './tests/browser.mjs';

const browser=await launch();
try {
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://127.0.0.1:8793/preview/preview.html?theme=old-big-picture');
  const root=page.locator('.dht-oldbigpicture:not([data-transition-snapshot])');
  const settled=()=>page.waitForFunction(()=>!document.querySelector('[data-transition-snapshot]'));
  await root.locator('.home-tile.library').click();await settled();
  const sidebar=root.locator('.library-sidebar');
  const expanded=await sidebar.evaluate(n=>n.getBoundingClientRect().width);
  const first=root.locator('.library-row .game').first();
  const appid=await first.getAttribute('data-appid');
  await first.focus();
  await page.waitForFunction(width=>document.querySelector('.dht-oldbigpicture:not([data-transition-snapshot]) .library-sidebar').getBoundingClientRect().width<width*.7,expanded);
  assert.equal(await root.getAttribute('data-page'),'library','Focus stays on the library page');
  assert.equal(await page.locator('[data-transition-snapshot]').count(),0,'Cover focus does not slide the page');
  await page.waitForFunction(()=>getComputedStyle(document.querySelector('.dht-oldbigpicture:not([data-transition-snapshot]) .library-row .game:focus .label')).backgroundColor==='rgb(59, 157, 187)');
  await page.keyboard.press('ArrowRight');
  await root.locator('.library-row .game:nth-child(2):focus').first().waitFor();
  await first.click();await root.locator('.classic-play').waitFor();await settled();
  await page.keyboard.press('Escape');await settled();
  assert.equal(await page.evaluate(()=>document.activeElement.dataset.appid),appid,'Back restores the selected title');
  await sidebar.getByRole('button',{name:'Resume & Explore',exact:true}).focus();
  await page.waitForFunction(width=>document.querySelector('.dht-oldbigpicture:not([data-transition-snapshot]) .library-sidebar').getBoundingClientRect().width>width*.95,expanded);
  await first.focus();
  mkdirSync('out/old-big-picture-reference',{recursive:true});
  await root.screenshot({path:'out/old-big-picture-reference/library.png'});
  await root.getByLabel('settings',{exact:true}).click();await settled();
  await root.screenshot({path:'out/old-big-picture-reference/settings.png'});
  await root.getByRole('button',{name:'Resolution',exact:true}).click();await settled();
  await root.getByRole('heading',{name:'Display',exact:true}).waitFor();
  assert.ok((await root.locator('dl').innerText()).includes('Screen resolution'));
  await page.keyboard.press('Escape');await settled();
  await root.getByRole('button',{name:'Disk Management',exact:true}).click();await settled();
  assert.ok(await root.locator('.disk-row').count()>0);
  await root.locator('.disk-row').first().click();
  await page.keyboard.press('Escape');
  await page.locator('.dht-destination').waitFor({state:'hidden'});
  await root.getByRole('heading',{name:'Disk Management',exact:true}).waitFor();
  await root.screenshot({path:'out/old-big-picture-reference/storage.png'});
  await root.getByRole('button',{name:'◉ Home',exact:true}).click();await settled();
  await root.getByLabel('power',{exact:true}).click();
  await root.getByRole('dialog',{name:'Power',exact:true}).waitFor();
  assert.equal(await root.getAttribute('data-page'),'home','Power menu overlays the home screen');
  assert.ok(await root.locator('main').evaluate(n=>n.inert));
  assert.equal(await page.evaluate(()=>document.activeElement.textContent),'Resume Big Picture');
  await root.screenshot({path:'out/old-big-picture-reference/power.png'});
  await page.keyboard.press('Escape');
  assert.equal(await root.getByRole('dialog').count(),0);
  assert.equal(await root.getByLabel('power',{exact:true}).evaluate(n=>n===document.activeElement),true);
  await root.locator('.home-tile.web').click();await settled();
  await root.getByLabel('Web address').fill('steamcommunity.com');
  await root.getByRole('button',{name:'Go',exact:true}).click();
  assert.equal(await root.getByRole('alert').count(),0);
  await page.emulateMedia({reducedMotion:'reduce'});
  await root.getByRole('button',{name:'◉ Home',exact:true}).click();
  await root.locator('.home-tile.library').click();await root.locator('.library-row .game').first().focus();
  assert.equal(await root.locator('.library-shell').evaluate(n=>getComputedStyle(n).transitionDuration),'0s');
  assert.equal(await page.locator('iframe').count(),0);
  assert.deepEqual(errors,[]);
  console.log('PASS: reference cover focus/sidebar motion, selected-title restoration, display/storage pages, modal power controls, URL entry and reduced motion.');
} finally {await browser.close();}
